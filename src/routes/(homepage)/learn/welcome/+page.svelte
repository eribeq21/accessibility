      <h1 class="mb-6 text-4xl font-bold text-blue-600">Digitale Barrierefreiheit</h1>
  
      <section class="space-y-4" id="a11y-definition">
        <h2 class="text-2xl font-bold text-gray-900">📌 Was ist digitale Barrierefreiheit?</h2>
  
        <p class="text-gray-700">
          Digitale Barrierefreiheit bedeutet, dass Webseiten und Apps so gestaltet werden, dass auch Menschen mit Behinderungen sie ohne Probleme nutzen können – zum Beispiel blinde, gehörlose oder körperlich eingeschränkte Menschen. <br />
          Es ist wichtig, dass man an verschiedene Behinderungen denkt und auf die Bedürfnisse der betroffenen Menschen hört.
        </p>
  
        <h3 class="text-xl font-semibold text-gray-800" id="warum-wichtig">🌍 Warum ist digitale Barrierefreiheit wichtig?</h3>
        <p class="text-gray-700">
          Über 1,3 Milliarden Menschen weltweit haben eine Behinderung. Wenn digitale Inhalte nicht barrierefrei sind, können diese Menschen viele Online-Dienste nicht nutzen, wie zum Beispiel Bestellungen auf Webseiten oder das Ansehen von Videos. <br />
          Barrierefreiheit hilft nicht nur Menschen mit Behinderungen, sondern auch älteren Menschen, denen mit gebrochenem Arm, Menschen in lauten Umgebungen und auch denen, die eine Sprache nicht gut verstehen.
        </p>
  
        <h3 class="text-xl font-semibold text-gray-800" id="wie-messen">🔧 Wie wird digitale Barrierefreiheit gemessen?</h3>
        <ul class="list-disc list-inside text-gray-700">
          <li>✅ Durch Accessibility-Tests, einschließlich automatisierter und manueller Tests.</li>
          <li>✅ Mit den Web Content Accessibility Guidelines (WCAG), die klare Erfolgsanforderungen definieren.</li>
          <li>✅ Anhand der POUR-Prinzipien (Perceivable, Operable, Understandable, Robust).</li>
        </ul>
  
        <h3 class="text-xl font-semibold text-gray-800" id="aria">📑 ARIA (Accessible Rich Internet Applications)</h3>
        <p class="text-gray-700">
          ARIA-Attribute verbessern die Zugänglichkeit von Webinhalten, besonders für Screenreader. Sie geben zusätzliche Informationen über die Rolle, den Zustand und die Eigenschaften von Elementen. <br />
          Wichtig: ARIA sollte nur verwendet werden, wenn HTML allein nicht ausreicht.
        </p>
  
        <h3 class="text-xl font-semibold text-gray-800" id="farbe-kontrast">🎨 Farbe wahrnehmen und Kontrast</h3>
        <p class="text-gray-700">
          Für gute Lesbarkeit muss ein ausreichender Kontrast zwischen Text und Hintergrund bestehen. Die Mindestanforderung nach WCAG ist: </p>
          <ul class="list-disc list-inside text-gray-700">
            <li>Normaler Text: mindestens 4.5:1</li>
            <li>Großer Text oder fette Icons: mindestens 3:1</li>
          </ul>
          <p>
              Wichtig: Farbenblindheit muss berücksichtigt werden, da Menschen Farben unterschiedlich wahrnehmen.
          </p>
  
        <h3 class="text-xl font-semibold text-gray-800" id="tools-testing">⚙️ Testing und Tools</h3>
        <p class="text-gray-700">
          Um die Barrierefreiheit zu testen, kann man Tools wie den **Color Contrast Analyzer** oder **Chrome DevTools** verwenden. <br />
          Zudem ist es hilfreich, die Seite in Graustufen anzusehen, um potenzielle Farbprobleme zu erkennen.
        </p>
  
        <h3 class="text-xl font-semibold text-gray-800" id="a11y-conclusion">✅ Fazit</h3>
        <p class="text-gray-700">
          Barrierefreiheit ist nicht nur für Menschen mit Behinderungen wichtig, sondern auch für alle Nutzer. Es hilft, mehr Menschen zu erreichen und sorgt für eine bessere Nutzererfahrung. Kleine Anpassungen wie richtige Farbkombinationen und die Verwendung von semantischem HTML machen einen großen Unterschied!
        </p>
